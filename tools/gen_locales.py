#!/usr/bin/env python3
"""Generate `crates/ultroid-core/src/locales.rs` from the Python source locales.

This is a *port*, not a copy: the locale *values* (user-facing text) are
preserved exactly, but the format is converted from YAML files into
idiomatic Rust — compile-time sorted slices looked up by binary search,
with per-language metadata as a typed struct. The generated file is the
shipped artefact; no .yml file is carried into the Rust repo.

Usage: python3 tools/gen_locales.py <source-strings-dir> <output-rs>
"""
import json
import sys
from pathlib import Path

import yaml


def rust_str(s: str) -> str:
    # json.dumps escapes are valid Rust string escapes when ensure_ascii=False
    # (\n, \t, \", \\); non-ASCII stays literal UTF-8.
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    src_dir = Path(sys.argv[1])
    out = Path(sys.argv[2])
    files = sorted(src_dir.glob("*.yml"))
    assert files, f"no .yml files in {src_dir}"

    lines = []
    lines.append("//! Locale strings — ported from `strings/strings/*.yml`.")
    lines.append("//!")
    lines.append("//! Generated by `tools/gen_locales.py` (run it again after editing")
    lines.append("//! the source locales). Values are preserved verbatim — they are")
    lines.append("//! user-facing text — but the format is idiomatic Rust: compile-time")
    lines.append("//! sorted slices, looked up by binary search. No YAML is shipped.")
    lines.append("")
    lines.append("/// Per-language metadata (the `name` / `natively` / `authors` keys).")
    lines.append("#[derive(Debug, Clone, Copy)]")
    lines.append("pub struct LanguageMeta {")
    lines.append("    pub code: &'static str,")
    lines.append("    pub name: &'static str,")
    lines.append("    pub natively: &'static str,")
    lines.append("    pub authors: &'static [&'static str],")
    lines.append("}")
    lines.append("")

    codes = []
    for f in files:
        code = f.stem.replace("-", "_")
        codes.append((f.stem, code))
        data = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        name = data.get("name", f.stem)
        natively = data.get("natively", name)
        authors = data.get("authors") or []
        authors = [str(a) for a in authors if a is not None]
        pairs = sorted(
            (str(k), str(v))
            for k, v in data.items()
            if k not in ("name", "natively", "authors") and isinstance(v, (str, int, float, bool))
        )
        const = code.upper()
        lines.append(f"pub static {const}: &[(&str, &str)] = &[")
        for k, v in pairs:
            lines.append(f"    ({rust_str(k)}, {rust_str(v)}),")
        lines.append("];")
        lines.append("")
        authors_rs = ", ".join(rust_str(a) for a in authors)
        lines.append(f"pub static {const}_META: LanguageMeta = LanguageMeta {{")
        lines.append(f"    code: {rust_str(f.stem)},")
        lines.append(f"    name: {rust_str(str(name))},")
        lines.append(f"    natively: {rust_str(str(natively))},")
        lines.append(f"    authors: &[{authors_rs}],")
        lines.append("};")
        lines.append("")

    lines.append("/// Look up a locale by code (`en`, `pt-br`, …). Returns the")
    lines.append("/// sorted (key, value) slice plus its metadata, or `None`.")
    lines.append("pub fn locale(lang: &str) -> Option<(&'static [(&'static str, &'static str)], &'static LanguageMeta)> {")
    lines.append("    match lang {")
    for stem, code in codes:
        const = code.upper()
        lines.append(f"        {rust_str(stem)} => Some(({const}, &{const}_META)),")
    lines.append("        _ => None,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("/// All shipped language codes, in source order.")
    all_codes = ", ".join(rust_str(stem) for stem, _ in codes)
    lines.append(f"pub static LANGUAGES: &[&str] = &[{all_codes}];")
    lines.append("")

    out.write_text("\n".join(lines), encoding="utf-8")
    total = sum(1 for _ in lines)
    print(f"wrote {out} ({len(codes)} locales, {total} lines)")


if __name__ == "__main__":
    main()
